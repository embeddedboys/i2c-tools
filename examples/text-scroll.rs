fn get_glyph(ch: char) -> &'static [u8; FONT_W] {
    let idx = ch as usize;
    if idx >= 0x20 && idx <= 0x7E {
        &FONT[idx - 0x20]
    } else {
        &FONT[0] // space for unknown chars
    }
}

/// Scroll a string across the display.
/// Each frame renders one column of the framebuffer to the matrix.
async fn scroll_text(
    columns: &mut [Output<'_>; COLS],
    rows: &mut [Output<'_>; ROWS],
    text: &[u8],
    offset: &mut i32,
) {
    let char_step = (FONT_W + CHAR_SPACING) as i32;
    let total_width = text.len() as i32 * char_step;
    let mut fb = [[false; COLS]; ROWS];

    // Build framebuffer from text at current scroll offset
    for scr_col in 0..COLS {
        let text_col = *offset + scr_col as i32;
        if text_col < 0 || text_col >= total_width {
            continue;
        }
        let char_idx = (text_col / char_step) as usize;
        let glyph_col = (text_col % char_step) as usize;
        if char_idx >= text.len() || glyph_col >= FONT_W {
            continue;
        }
        let ch = text[char_idx] as char;
        let glyph = get_glyph(ch);
        let col_bits = glyph[glyph_col];
        for row in 0..ROWS {
            if col_bits & (1 << (ROWS - 1 - row)) != 0 {
                fb[row][scr_col] = true;
            }
        }
    }

    // Scan matrix
    for row in 0..ROWS {
        for col in 0..COLS {
            if fb[row][col] {
                columns[col].set_high();
            }
        }
        rows[row].set_high();
        Timer::after_micros(500).await;
        rows[row].set_low();
        for col in columns.iter_mut() {
            col.set_low();
        }
    }

    *offset += 1;
    if *offset >= total_width + COLS as i32 {
        *offset = -(COLS as i32); // wrap around with a gap
    }
}

#[embassy_executor::main(entry = "ch32_hal::entry")]
async fn main(_spawner: Spawner) -> ! {
    let mut config = ch32_hal::Config::default();
    config.rcc = ch32_hal::rcc::Config::SYSCLK_FREQ_144MHZ_HSE;
    let p = ch32_hal::init(config);

    let mut columns = [
        Output::new(p.PB5, Level::Low, Speed::Low),
        Output::new(p.PB4, Level::Low, Speed::Low),
        Output::new(p.PB3, Level::Low, Speed::Low),
        Output::new(p.PA15, Level::Low, Speed::Low),
        Output::new(p.PA0, Level::Low, Speed::Low),
        Output::new(p.PA1, Level::Low, Speed::Low),
        Output::new(p.PA12, Level::Low, Speed::Low),
        Output::new(p.PA11, Level::Low, Speed::Low),
        Output::new(p.PA10, Level::Low, Speed::Low),
        Output::new(p.PA9, Level::Low, Speed::Low),
        Output::new(p.PA8, Level::Low, Speed::Low),
        Output::new(p.PB15, Level::Low, Speed::Low),
        Output::new(p.PB14, Level::Low, Speed::Low),
        Output::new(p.PB13, Level::Low, Speed::Low),
        Output::new(p.PB12, Level::Low, Speed::Low),
        Output::new(p.PB11, Level::Low, Speed::Low),
    ];

    let mut rows = [
        Output::new(p.PA3, Level::Low, Speed::Low),
        Output::new(p.PA4, Level::Low, Speed::Low),
        Output::new(p.PA5, Level::Low, Speed::Low),
        Output::new(p.PA6, Level::Low, Speed::Low),
        Output::new(p.PA7, Level::Low, Speed::Low),
        Output::new(p.PB0, Level::Low, Speed::Low),
        Output::new(p.PB1, Level::Low, Speed::Low),
        Output::new(p.PB10, Level::Low, Speed::Low),
    ];
    let text = b"There it is. The Wishing Portal.\
They say for your wish to come true, \
you have to give up something really important. \
For me, that's my panini maker. \
I wish for a millon sandwiches. \
None of those things are gonna happen, you know. \
Morty wishes never come true. Not on the citadel. \
Then why did you bring us here? \
Because I wish that would change. \
I wish anything about this life would change. \
Well, I hope you're putting something pretty goddamn important in there. \
Me too. But i doubt it. \
!@#$%^&*()_+-=[]{}|\\;:',./<>?";
    let mut offset: i32 = -(COLS as i32);

    loop {
        scroll_text(&mut columns, &mut rows, text, &mut offset).await;
        Timer::after_millis(60).await;
    }
}
